// Runs the rule-based parser over data/parser-testset.json and prints accuracy.
// Usage: npm run eval:parser   (writes docs/parser-eval.md as well)

import { readFileSync, writeFileSync } from "node:fs";
import { evaluate, pct, type TestCase } from "../src/lib/parser/evaluate.ts";
import { parseOrder } from "../src/lib/parser/parse.ts";

const data = JSON.parse(readFileSync(new URL("../data/parser-testset.json", import.meta.url), "utf8")) as { cases: TestCase[] };
const { results, summary } = evaluate(data.cases, parseOrder);
const verbose = process.argv.includes("--verbose");

for (const r of results) {
  if (r.pass && !verbose) continue;
  console.log(`${r.pass ? "PASS" : "FAIL"} ${r.id} [${r.split}] ${JSON.stringify(r.message)}`);
  if (!r.pass) {
    for (const m of r.missing) console.log(`   missing  ${m}`);
    for (const e of r.extra) console.log(`   extra    ${e}`);
    if (!r.duePass) console.log(`   due      expected ${r.expected.due} got ${r.got.due}`);
  }
}

const s = summary;
const line = (name: string, t: { total: number; passed: number }) => `${name.padEnd(10)} ${t.passed}/${t.total} (${pct(t)}%)`;
console.log("");
console.log(line("all", s.cases));
console.log(line("dev", s.dev));
console.log(line("holdout", s.holdout));
console.log(line("english", s.english));
console.log(line("hinglish", s.hinglish));
console.log(line("due date", s.due));
const precision = s.lines.predicted ? Math.round((100 * s.lines.correct) / s.lines.predicted) : 0;
const recall = s.lines.expected ? Math.round((100 * s.lines.correct) / s.lines.expected) : 0;
console.log(`lines      ${s.lines.correct}/${s.lines.expected} expected lines found, precision ${precision}%, recall ${recall}%`);

if (process.argv.includes("--write")) {
  const failures = results.filter((r) => !r.pass);
  const md = [
    "# Parser evaluation",
    "",
    "Generated by `npm run eval:parser`. The parser is rule-based (no LLM).",
    "",
    "| Set | Messages fully correct |",
    "| --- | --- |",
    `| All | **${s.cases.passed}/${s.cases.total}** (${pct(s.cases)}%) |`,
    `| Dev (rules written against these) | ${s.dev.passed}/${s.dev.total} |`,
    `| Holdout (written first, kept aside) | ${s.holdout.passed}/${s.holdout.total} |`,
    `| English | ${s.english.passed}/${s.english.total} |`,
    `| Hinglish | ${s.hinglish.passed}/${s.hinglish.total} |`,
    `| Due date | ${s.due.passed}/${s.due.total} |`,
    "",
    `Line items: ${s.lines.correct} of ${s.lines.expected} expected lines found; precision ${precision}%, recall ${recall}%.`,
    "",
    "A message counts as correct only if every line (product, colour, size, quantity) and the due date match exactly.",
    "",
    "## Failures",
    "",
    ...(failures.length
      ? failures.flatMap((r) => [
          `- **${r.id}** (${r.split}) \`${r.message.replace(/\n/g, " / ")}\``,
          ...r.missing.map((m) => `  - missing: ${m}`),
          ...r.extra.map((e) => `  - extra: ${e}`),
          ...(r.duePass ? [] : [`  - due: expected ${r.expected.due}, got ${r.got.due}`]),
        ])
      : ["None."]),
    "",
  ].join("\n");
  writeFileSync(new URL("../docs/parser-eval.md", import.meta.url), md);
  console.log("wrote docs/parser-eval.md");
}
